const generatedTestHeader = "// Code generated by tools/gen-cldr; DO NOT EDIT.\n"

func TestCompareGeneratedDataRejectsMissingFreshPath(t *testing.T) {
	t.Parallel()

	committed := t.TempDir()
	generated := t.TempDir()
	writeGeneratedTestFile(t, committed, "cldr/number/data.go", generatedTestHeader+"package number\n")

	err := compareGeneratedData(committed, generated)
	if err == nil || !strings.Contains(err.Error(), "cldr/number/data.go") {
		t.Fatalf("compareGeneratedData() error = %v, want missing path", err)
	}
}

