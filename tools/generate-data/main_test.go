func TestGenerationFailurePreservesTargets(t *testing.T) {
	repo, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(filepath.Join(repo, "tools", "gen-cldr", ".cldr-json", "node_modules", "cldr-core", "supplemental", "plurals.json")); os.IsNotExist(err) {
		t.Skip("pinned CLDR inputs are required by task modules:verify")
	}
	for _, mode := range []string{"auxiliary", "missing plural", "malformed plural"} {
		t.Run(mode, func(t *testing.T) {
			root := generationRoot(t, repo)
			before, err := generateddata.Read(filepath.Join(root, "internal"))
			if err != nil {
				t.Fatal(err)
			}
			stage := t.TempDir()
			plurals := filepath.Join(repo, "tools", "gen-cldr", ".cldr-json", "node_modules", "cldr-core", "supplemental", "plurals.json")
			switch mode {
			case "auxiliary":
				writeTestFile(t, filepath.Join(stage, "internal", "localeid"), "blocked")
			case "missing plural":
				plurals = filepath.Join(t.TempDir(), "missing.json")
			case "malformed plural":
				plurals = filepath.Join(t.TempDir(), "plurals.json")
				writeTestFile(t, plurals, "{")
			}
			if err := generate(t.Context(), root, stage, plurals); err == nil {
				t.Fatal("generation unexpectedly succeeded")
			}
			after, err := generateddata.Read(filepath.Join(root, "internal"))
			if err != nil {
				t.Fatal(err)
			}
			if !maps.EqualFunc(before, after, bytes.Equal) {
				t.Fatal("failed generation changed target paths or bytes")
			}
			// The failure was reached after CLDR runtime output had been generated.
			if _, err := os.Stat(filepath.Join(stage, "internal", "cldr", "number", "data.go")); err != nil {
				t.Fatal(err)
			}
		})
	}
}

func TestInstallPreservesHandwrittenFiles(t *testing.T) {
	target, candidate := t.TempDir(), t.TempDir()
	writeTestFile(t, filepath.Join(target, "number", "obsolete.go"), "// Code generated by tools/gen-cldr; DO NOT EDIT.\nold")
	writeTestFile(t, filepath.Join(target, "number", "decode.go"), "handwritten")
	writeTestFile(t, filepath.Join(candidate, "number", "data.go"), "// Code generated by tools/gen-cldr; DO NOT EDIT.\nfresh")
	if err := install(target, candidate); err != nil {
		t.Fatal(err)
	}
	actual, err := generateddata.Read(target)
	if err != nil {
		t.Fatal(err)
	}
	expected, err := generateddata.Read(candidate)
	if err != nil {
		t.Fatal(err)
	}
	if !maps.EqualFunc(actual, expected, bytes.Equal) {
		t.Fatal("installed set differs from candidate")
	}
	if data, err := os.ReadFile(filepath.Join(target, "number", "decode.go")); err != nil || string(data) != "handwritten" {
		t.Fatal("handwritten file changed")
	}
	writeTestFile(t, filepath.Join(candidate, "number", "decode.go"), "// Code generated by tools/gen-cldr; DO NOT EDIT.\ncollision")
	if err := install(target, candidate); err == nil || !strings.Contains(err.Error(), "handwritten") {
		t.Fatalf("collision not rejected: %v", err)
	}
}

func generationRoot(t *testing.T, repo string) string {
	t.Helper()
	root := t.TempDir()
	if err := os.Symlink(filepath.Join(repo, "tools"), filepath.Join(root, "tools")); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(filepath.Join(repo, "internal", "cldr", "VERSION"))
	if err != nil {
		t.Fatal(err)
	}
	writeTestFile(t, filepath.Join(root, "internal", "cldr", "VERSION"), string(data))
	writeTestFile(t, filepath.Join(root, "internal", "cldr", "number", "data.go"), "// Code generated by tools/gen-cldr; DO NOT EDIT.\nold")
	writeTestFile(t, filepath.Join(root, "internal", "cldr", "number", "decode.go"), "handwritten")
	return root
}
func writeTestFile(t *testing.T, path, data string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(data), 0o600); err != nil {
		t.Fatal(err)
	}
}
